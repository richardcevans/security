#!/usr/bin/env bash
# Attach this lab to an existing, working adb-oci-iam environment.

set -Eeuo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck disable=SC1091 # Resolved from this script's directory at runtime.
source "${script_dir}/../lib/common.sh"

usage() {
  cat <<'EOF'
Usage: ./bin/attach-adb-oci-iam.sh --env-file PATH

Records a reference to an existing adb-oci-iam generated environment. This does
not create, alter, import, or take Terraform ownership of the ADB, IAM users,
groups, OAuth apps, wallet, or HR/Deep Sec objects. Passwords and OAuth client
secrets are never copied into this lab's state.
EOF
}

environment_file=''
while [[ $# -gt 0 ]]; do
  case "$1" in
    --env-file)
      [[ $# -ge 2 ]] || { usage >&2; exit 2; }
      environment_file=$2
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

[[ -n "$environment_file" ]] || die 'Attachment requires --env-file PATH.'
[[ -f "$environment_file" ]] || die "adb-oci-iam environment file not found: ${environment_file}"
environment_file=$(cd "$(dirname "$environment_file")" && pwd)/$(basename "$environment_file")

# shellcheck disable=SC1090 # User selected a generated adb-oci-iam environment.
source "$environment_file"
for variable in ADB_OCID DB_NAME ADB_SERVICE TNS_ADMIN WALLET_DIR OCI_DOMAIN_URL OCI_DB_APP_ID OCI_CLIENT_APP_ID OCI_SCOPE OCI_TOKEN_DIR; do
  [[ -n "${!variable:-}" ]] || die "Attached environment is missing ${variable}: ${environment_file}"
done
for wallet_file in tnsnames.ora sqlnet.ora cwallet.sso ewallet.p12; do
  [[ -f "${TNS_ADMIN}/${wallet_file}" ]] || die "Attached wallet is missing ${TNS_ADMIN}/${wallet_file}"
done

mkdir -p "$LAB_STATE_DIR"
attachment_file="${LAB_STATE_DIR}/attached-adb.env"
{
  printf '# Generated by attach-adb-oci-iam.sh. Do not add secrets.\n'
  printf 'export LEGACY_ENV_FILE=%q\n' "$environment_file"
  printf 'export ATTACHED_ADB_OCID=%q\n' "$ADB_OCID"
  printf 'export ATTACHED_DB_NAME=%q\n' "$DB_NAME"
  printf 'export ATTACHED_ADB_SERVICE=%q\n' "$ADB_SERVICE"
  printf 'export ATTACHED_TNS_ADMIN=%q\n' "$TNS_ADMIN"
  printf 'export ATTACHED_WALLET_DIR=%q\n' "$WALLET_DIR"
  printf 'export ATTACHED_OCI_DOMAIN_URL=%q\n' "$OCI_DOMAIN_URL"
  printf 'export ATTACHED_OCI_DB_APP_ID=%q\n' "$OCI_DB_APP_ID"
  printf 'export ATTACHED_OCI_CLIENT_APP_ID=%q\n' "$OCI_CLIENT_APP_ID"
  printf 'export ATTACHED_OCI_SCOPE=%q\n' "$OCI_SCOPE"
  printf 'export ATTACHED_OCI_TOKEN_DIR=%q\n' "$OCI_TOKEN_DIR"
  printf 'export ATTACHED_AT_UTC=%q\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
} >"$attachment_file"
chmod 600 "$attachment_file"

info 'Attached this GenAI lab to the existing adb-oci-iam baseline.'
info "ADB:     ${DB_NAME} (${ADB_OCID})"
info "Service: ${ADB_SERVICE}"
info "State:   ${attachment_file}"
info 'Next: ./bin/labctl baseline --expect-user <IAM-user>'
