#!/usr/bin/env bash
# Give the attached ADB resource principal permission to make GenAI chat calls.

set -Eeuo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck disable=SC1091 # Resolved from this script's directory at runtime.
source "${script_dir}/../lib/common.sh"

usage() {
  cat <<'EOF'
Usage: ./bin/configure-select-ai-access.sh [--compartment-id OCID]

Creates or reuses a dynamic group matching only the attached ADB, then creates
or reuses a tenancy policy allowing that dynamic group to use OCI Generative AI
Chat in the GenAI lab compartment. It grants no Object Storage, IAM, or broad
Generative AI family permissions.
EOF
}

compartment_id=''
while [[ $# -gt 0 ]]; do
  case "$1" in
    --compartment-id)
      [[ $# -ge 2 ]] || { usage >&2; exit 2; }
      compartment_id=$2
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

load_legacy_environment
# shellcheck disable=SC1091 # Shared OCI CLI profile selector from the attached lab.
source "${LEGACY_LAB_ROOT}/lib_oci_profile.sh"
require_command oci

if [[ -z "$compartment_id" ]]; then
  compartment_id=${ROOT_COMP_ID:-${COMPARTMENT_OCID:-}}
fi
if [[ -z "$compartment_id" && -f "${LAB_STATE_DIR}/genai.env" ]]; then
  # shellcheck disable=SC1091 # Written only by create-genai-compartment.sh.
  source "${LAB_STATE_DIR}/genai.env"
  compartment_id=${COMPARTMENT_OCID:-}
fi
[[ -n "$compartment_id" ]] || die 'No compartment is configured. Set OCI_COMPARTMENT/ROOT_COMP_ID in adb-oci-iam or provide --compartment-id.'
[[ -n "${ADB_OCID:-}" && -n "${TENANCY_OCID:-}" ]] || die 'The attached adb-oci-iam environment lacks ADB_OCID or TENANCY_OCID.'

dynamic_group_name='deep-sec-gen-ai-adb-rp'
policy_name='deep-sec-gen-ai-adb-chat'
matching_rule="resource.id = '${ADB_OCID}'"
policy_statement="Allow dynamic-group ${dynamic_group_name} to use generative-ai-chat in compartment id ${compartment_id}"

mapfile -t dynamic_group_ids < <(
  oci_with_profile iam dynamic-group list \
    --compartment-id "$TENANCY_OCID" \
    --name "$dynamic_group_name" \
    --lifecycle-state ACTIVE \
    --all \
    --query 'data[].id' \
    --raw-output
)

case ${#dynamic_group_ids[@]} in
  0)
    info "Creating dynamic group ${dynamic_group_name} for the attached ADB."
    dynamic_group_id=$(oci_with_profile iam dynamic-group create \
      --compartment-id "$TENANCY_OCID" \
      --name "$dynamic_group_name" \
      --description 'Resource principal for the attached ADB Select AI chat profile.' \
      --matching-rule "$matching_rule" \
      --wait-for-state ACTIVE \
      --query 'data.id' \
      --raw-output)
    dynamic_group_created=1
    ;;
  1)
    dynamic_group_id=${dynamic_group_ids[0]}
    current_rule=$(oci_with_profile iam dynamic-group get \
      --dynamic-group-id "$dynamic_group_id" \
      --query 'data."matching-rule"' \
      --raw-output)
    [[ "$current_rule" == "$matching_rule" ]] || die "Existing dynamic group ${dynamic_group_name} does not match the attached ADB. It was not changed."
    dynamic_group_created=0
    info "Reusing dynamic group ${dynamic_group_name}: ${dynamic_group_id}"
    ;;
  *) die "Found multiple active dynamic groups named ${dynamic_group_name}." ;;
esac

mapfile -t policy_ids < <(
  oci_with_profile iam policy list \
    --compartment-id "$TENANCY_OCID" \
    --name "$policy_name" \
    --lifecycle-state ACTIVE \
    --all \
    --query 'data[].id' \
    --raw-output
)

case ${#policy_ids[@]} in
  0)
    info "Creating least-privilege Select AI chat policy ${policy_name}."
    policy_id=$(oci_with_profile iam policy create \
      --compartment-id "$TENANCY_OCID" \
      --name "$policy_name" \
      --description 'Allow only the attached ADB resource principal to call OCI Generative AI Chat in the demo compartment.' \
      --statements "[\"${policy_statement}\"]" \
      --wait-for-state ACTIVE \
      --query 'data.id' \
      --raw-output)
    policy_created=1
    ;;
  1)
    policy_id=${policy_ids[0]}
    existing_statements=$(oci_with_profile iam policy get \
      --policy-id "$policy_id" \
      --query 'data.statements' \
      --output json)
    [[ "$existing_statements" == *"$policy_statement"* ]] || die "Existing policy ${policy_name} does not contain the required statement. It was not changed."
    policy_created=0
    info "Reusing Select AI chat policy ${policy_name}: ${policy_id}"
    ;;
  *) die "Found multiple active policies named ${policy_name}." ;;
esac

mkdir -p "$LAB_STATE_DIR"
state_file="${LAB_STATE_DIR}/select-ai-access.env"
umask 077
cat >"$state_file" <<EOF
# Generated by configure-select-ai-access.sh; safe to source.
export SELECT_AI_DYNAMIC_GROUP_NAME='${dynamic_group_name}'
export SELECT_AI_DYNAMIC_GROUP_ID='${dynamic_group_id}'
export SELECT_AI_POLICY_NAME='${policy_name}'
export SELECT_AI_POLICY_ID='${policy_id}'
export SELECT_AI_GENAI_COMPARTMENT_OCID='${compartment_id}'
export SELECT_AI_DYNAMIC_GROUP_CREATED='${dynamic_group_created}'
export SELECT_AI_POLICY_CREATED='${policy_created}'
EOF
chmod 600 "$state_file"

printf '\nSelect AI OCI access is configured. State: %s\n' "$state_file"
printf 'Dynamic group: %s\nPolicy statement: %s\n' "$dynamic_group_name" "$policy_statement"
printf '%s\n' 'Important: Autonomous Database resource-principal tokens can be cached for up to two hours after IAM policy or dynamic-group changes.'
printf '%s\n' 'Next: ./bin/labctl select-ai configure'
