#!/usr/bin/env bash
# Select the attached ADB lab compartment for this GenAI extension.

set -Eeuo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck disable=SC1091 # Resolved from this script's directory at runtime.
source "${script_dir}/../lib/common.sh"

usage() {
  cat <<'EOF'
Usage: ./bin/create-genai-compartment.sh [options]

By default, records the same compartment selected by the attached adb-oci-iam
lab (`ROOT_COMP_ID`, resolved from `OCI_COMPARTMENT`). On success it writes:

  .lab/genai.env

Load that file before the GenAI smoke test to set COMPARTMENT_OCID.

Options:
  --name NAME                 Create or reuse a dedicated child compartment instead.
  --parent-compartment-id ID  Parent OCID for --name (default: attached tenancy).
  --help                      Show this help.
EOF
}

compartment_name=''
parent_compartment_id=''
while [[ $# -gt 0 ]]; do
  case "$1" in
    --name)
      [[ $# -ge 2 ]] || { usage >&2; exit 2; }
      compartment_name=$2
      shift 2
      ;;
    --parent-compartment-id)
      [[ $# -ge 2 ]] || { usage >&2; exit 2; }
      parent_compartment_id=$2
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

load_legacy_environment
# shellcheck disable=SC1091 # Shared OCI CLI profile selector from the attached lab.
source "${LEGACY_LAB_ROOT}/lib_oci_profile.sh"
require_command oci

if [[ -z "$compartment_name" ]]; then
  compartment_id=${ROOT_COMP_ID:-}
  [[ -n "$compartment_id" ]] || die 'The attached adb-oci-iam environment lacks ROOT_COMP_ID. Set OCI_COMPARTMENT or ROOT_COMP_ID when running 00_setup_adb.sh.'
  compartment_name=${OCI_COMPARTMENT:-$compartment_id}
  created=0
  info "Using the attached ADB lab compartment: ${compartment_id}"
else
  parent_compartment_id=${parent_compartment_id:-${TENANCY_OCID:-}}
  [[ -n "$parent_compartment_id" ]] || die 'No parent compartment was supplied and TENANCY_OCID is absent from the attached environment.'

  mapfile -t matching_ids < <(
  oci_with_profile iam compartment list \
    --compartment-id "$parent_compartment_id" \
    --name "$compartment_name" \
    --lifecycle-state ACTIVE \
    --all \
    --query 'data[].id' \
    --raw-output
  )

  case ${#matching_ids[@]} in
  0)
    info "Creating compartment ${compartment_name} under ${parent_compartment_id}."
    compartment_id=$(oci_with_profile iam compartment create \
      --compartment-id "$parent_compartment_id" \
      --name "$compartment_name" \
      --description 'Resources owned by the deep-sec-gen-ai-demo lab.' \
      --freeform-tags '{"lab":"deep-sec-gen-ai-demo","managed-by":"lab-script"}' \
      --wait-for-state ACTIVE \
      --query 'data.id' \
      --raw-output)
    created=1
    ;;
  1)
    compartment_id=${matching_ids[0]}
    created=0
    info "Reusing active compartment ${compartment_name}: ${compartment_id}"
    ;;
    *)
      die "Found multiple active direct children named ${compartment_name} under ${parent_compartment_id}; choose a distinct --name."
      ;;
  esac
fi

[[ -n "$compartment_id" && "$compartment_id" != 'null' ]] || die 'OCI did not return a compartment OCID.'
mkdir -p "$LAB_STATE_DIR"
state_file="${LAB_STATE_DIR}/genai.env"
umask 077
cat >"$state_file" <<EOF
# Generated by create-genai-compartment.sh; safe to source.
export COMPARTMENT_OCID='${compartment_id}'
export TENANCY_OCID='${TENANCY_OCID}'
export GENAI_COMPARTMENT_NAME='${compartment_name}'
export GENAI_COMPARTMENT_CREATED='${created}'
export GENAI_COMPARTMENT_SOURCE='OCI_COMPARTMENT'
EOF
chmod 600 "$state_file"

printf '\nGenAI compartment ready: %s\n' "$compartment_id"
printf 'Environment file: %s\n' "$state_file"
printf 'Next:\n  source %q\n' "$state_file"
printf '  ./bin/labctl genai smoke --compartment-id "$%s"\n' 'COMPARTMENT_OCID'
