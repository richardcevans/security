#!/usr/bin/env bash
# Read-only gate before creating GenAI-lab-owned resources or objects.

set -Eeuo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck disable=SC1091 # Resolved from this script's directory at runtime.
source "${script_dir}/../lib/common.sh"

usage() {
  cat <<'EOF'
Usage: ./bin/verify-attached-baseline.sh --expect-user USER [--require-group GROUP]...

Verifies the attached adb-oci-iam ADMIN configuration and then verifies the
current OAuth token as the specified IAM user. This command is read-only.
EOF
}

expected_user=''
group_args=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --expect-user)
      [[ $# -ge 2 ]] || { usage >&2; exit 2; }
      expected_user=$2
      shift 2
      ;;
    --require-group)
      [[ $# -ge 2 ]] || { usage >&2; exit 2; }
      group_args+=(--require-group "$2")
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

[[ -n "$expected_user" ]] || die 'Baseline verification requires --expect-user USER.'
attachment_file="${LAB_STATE_DIR}/attached-adb.env"
[[ -f "$attachment_file" ]] || die 'No ADB attachment exists. Run ./bin/labctl attach --env-file ../adb-oci-iam/.adb-oci-iam.env first.'

load_legacy_environment
info "Attached ADB: ${DB_NAME} (${ADB_SERVICE})"
info 'Checking the inherited ADMIN-side OCI IAM and Deep Sec configuration.'
run_legacy_script verify_db_setup.sh

info 'Checking the current OAuth token and direct session as the expected IAM user.'
run_legacy_script 08_verify_current_token.sh --expect-user "$expected_user" "${group_args[@]}"

baseline_file="${LAB_STATE_DIR}/baseline-passed.env"
{
  printf '# Generated by verify-attached-baseline.sh.\n'
  printf 'export BASELINE_EXPECTED_USER=%q\n' "$expected_user"
  printf 'export BASELINE_VERIFIED_AT_UTC=%q\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf 'export BASELINE_ADB_OCID=%q\n' "$ADB_OCID"
} >"$baseline_file"
chmod 600 "$baseline_file"

info 'Attached adb-oci-iam baseline verification passed.'
